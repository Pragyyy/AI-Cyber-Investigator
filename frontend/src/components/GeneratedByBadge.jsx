const LABELS = {
  llm: "LLM",
  fallback: "Deterministic fallback",
  fallback_parse_error: "Fallback (parse error)",
};

// Small transparency badge showing whether an agent's output came from a real LLM
// call or the deterministic fallback - surfaces the pipeline's own "generated_by"
// tagging (see backend/app/agents/nodes.py) directly in the UI.
export default function GeneratedByBadge({ generatedBy }) {
  if (!generatedBy) return null;
  const isLlm = generatedBy === "llm";
  return (
    <span
      className={`badge-generated ${isLlm ? "llm" : ""}`}
      title={isLlm ? "Generated by a real LLM call" : "No LLM configured or the call failed; used the deterministic fallback"}
    >
      {isLlm ? "●" : "○"} {LABELS[generatedBy] || generatedBy}
    </span>
  );
}
